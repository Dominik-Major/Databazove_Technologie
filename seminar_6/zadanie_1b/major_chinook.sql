CREATE TABLE public.dim_customer (
    customer_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_customer_id INTEGER NOT NULL UNIQUE,
    first_name VARCHAR(40) NOT NULL,
    last_name VARCHAR(20) NOT NULL,
    company VARCHAR(80),
    city VARCHAR(40),
    state VARCHAR(40),
    country VARCHAR(40),
    postal_code VARCHAR(10)
);

CREATE TABLE public.dim_track (
    track_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_track_id INTEGER NOT NULL UNIQUE,
    track_name VARCHAR(200) NOT NULL,
    album_title VARCHAR(160),
    artist_name VARCHAR(120),
    genre_name VARCHAR(120),
    media_type_name VARCHAR(120),
    composer VARCHAR(220),
    milliseconds INTEGER,
    bytes INTEGER
);

CREATE TABLE public.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    day_of_month SMALLINT NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    month_number SMALLINT NOT NULL CHECK (month_number BETWEEN 1 AND 12),
    quarter_number SMALLINT NOT NULL CHECK (quarter_number BETWEEN 1 AND 4),
    year_number SMALLINT NOT NULL
);

CREATE TABLE public.dim_billing_location (
    location_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_address VARCHAR(70),
    billing_city VARCHAR(40),
    billing_state VARCHAR(40),
    billing_country VARCHAR(40),
    billing_postal_code VARCHAR(10)
);

CREATE TABLE public.fact_sales (
    sales_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_invoice_line_id INTEGER NOT NULL UNIQUE,
    source_invoice_id INTEGER NOT NULL,
    customer_key INTEGER NOT NULL,
    track_key INTEGER NOT NULL,
    date_key INTEGER NOT NULL,
    location_key INTEGER NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    total_amount NUMERIC(14,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    CONSTRAINT fk_sales_customer FOREIGN KEY (customer_key)
        REFERENCES public.dim_customer(customer_key),
    CONSTRAINT fk_sales_track FOREIGN KEY (track_key)
        REFERENCES public.dim_track(track_key),
    CONSTRAINT fk_sales_date FOREIGN KEY (date_key)
        REFERENCES public.dim_date(date_key),
    CONSTRAINT fk_sales_location FOREIGN KEY (location_key)
        REFERENCES public.dim_billing_location(location_key)
);

CREATE INDEX idx_fact_sales_customer ON public.fact_sales(customer_key);
CREATE INDEX idx_fact_sales_track ON public.fact_sales(track_key);
CREATE INDEX idx_fact_sales_date ON public.fact_sales(date_key);
CREATE INDEX idx_fact_sales_location ON public.fact_sales(location_key);
CREATE INDEX idx_fact_sales_invoice ON public.fact_sales(source_invoice_id);